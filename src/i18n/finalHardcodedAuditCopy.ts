export function getFinalHardcodedAuditCopy(language: Language) {
  return finalHardcodedAuditCopy[language];
}

export function formatFinalAuditCopy(template: string, params: Record<string, string | number>) {
  return template.replace(/{{\s*([^}\s]+)\s*}}/g, (_match, token: string) => {
    const value = params[token];
    return value === undefined ? `{{${token}}}` : String(value);
  });
}
